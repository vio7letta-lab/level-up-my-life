import type { Difficulty, StatKey } from '../types'

// Важно: в JavaScript \b не работает с кириллицей, поэтому границы слов
// записаны явно: (?<![а-яёa-z]) — «перед словом не буква», (?![а-яёa-z]) — «после слова не буква».

/**
 * Правила автоопределения категории и сложности задачи по тексту.
 * Без ИИ: обычные регулярные выражения по основам русских слов.
 * Если правило ошиблось — категорию и сложность всегда можно поменять вручную.
 *
 * Порядок важен: срабатывает первое подходящее правило.
 */

export interface StatRule {
  pattern: RegExp
  stat: StatKey
  /** привязать задачу к цели этой характеристики (по умолчанию — да) */
  linkGoal?: boolean
}

